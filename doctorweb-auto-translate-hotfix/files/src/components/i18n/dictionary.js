export function normalizePersianText(value) {
  return String(value || '')
    .replace(/\u200c/g, '‌')
    .replace(/\s+/g, ' ')
    .trim();
}

export function translateVisibleText(text, locale) {
  if (locale === 'fa') return text;

  const dictionary = UI_DICTIONARY[locale] || {};
  const normalized = normalizePersianText(text);

  if (!normalized) return text;
  if (dictionary[normalized]) return dictionary[normalized];

  let translated = text;

  Object.entries(dictionary)
    .sort(([a], [b]) => b.length - a.length)
    .forEach(([source, target]) => {
      if (source.length < 4) return;
      if (translated.includes(source)) {
        translated = translated.split(source).join(target);
      }
    });

  return translated;
}
